package com.wu.pharos.uam.ingestion.service;

import static com.wu.pharos.uam.common.error.ApiException.invalid;
import static com.wu.pharos.uam.common.error.ApiException.rule;
import com.wu.pharos.uam.ingestion.model.EmployeeEvent;
import com.wu.pharos.uam.ingestion.model.EventType;
import jakarta.validation.Validator;
import jakarta.validation.constraints.Email;
import java.time.Clock;
import java.time.Instant;
import java.time.LocalDate;
import java.time.OffsetDateTime;
import java.time.format.DateTimeParseException;
import java.util.HashSet;
import java.util.Set;
import java.util.UUID;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Component;
import tools.jackson.databind.JsonNode;

@Component
public class EventValidator {
  private static final Set<String> ENVELOPE = Set.of("eventId", "eventType", "eventEffectiveAt", "environment", "user");
  private static final Set<String> PROFILE = Set.of("employeeId", "sourceSystem", "firstName", "middleName", "lastName", "email",
      "employmentStatus", "hireDate", "terminationDate", "employmentType", "employeeClass", "account", "superiorOrganization",
      "organizationId", "country", "region", "site", "supervisoryOrganization", "employeeLastSyncedAt", "manager", "iPassRoles");
  private static final Set<String> MANAGER = Set.of("employeeId", "firstName", "middleName", "lastName", "displayName", "email");
  private static final Set<String> ROLE = Set.of("entitlementValue", "entitlementType", "roleName", "displayName", "roleDescription",
      "isPharosGroup", "isAvailableForRequest", "isPrivileged", "owners", "assignedAt", "assignmentStatus");
  private static final Set<String> ACCOUNT = Set.of("application", "oktaAccountId");
  private static final Set<String> OWNER = Set.of("ownerId", "firstName", "lastName", "email");
  private final String environment;
  private final Clock clock;
  private final Validator validator;

  public EventValidator(@Value("${uam.environment}") String environment, Clock clock, Validator validator) {
    if (!Set.of("Prod", "UAT", "Dev").contains(environment)) {
      throw new IllegalArgumentException("Invalid UAM_ENVIRONMENT");
    }
    this.environment = environment;
    this.clock = clock;
    this.validator = validator;
  }

  public EmployeeEvent envelope(JsonNode root) {
    fields(root, ENVELOPE, "request");
    String id = text(root, "eventId");
    if (!id.matches("(?i)[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}")) {
      throw invalid("eventId must be a UUID generated by iPass");
    }
    EventType type;
    try {
      type = EventType.valueOf(text(root, "eventType"));
    } catch (IllegalArgumentException e) {
      throw invalid("Unsupported eventType");
    }
    String env = text(root, "environment");
    if (!environment.equals(env)) {
      throw rule("Request environment does not match this deployment");
    }
    Instant eventEffectiveAt = timestamp(root, "eventEffectiveAt");
    if (eventEffectiveAt.isAfter(clock.instant().plusSeconds(60))) {
      throw rule("eventEffectiveAt cannot be in the future");
    }
    JsonNode user = root.get("user");
    if (user == null || !user.isObject()) {
      throw invalid("user must be an object");
    }
    String employeeId = identifier(user, "employeeId");
    return new EmployeeEvent(UUID.fromString(id), type, eventEffectiveAt, env, employeeId, user, root);
  }

  public void validate(EmployeeEvent event) {
    JsonNode user = event.user();
    if (event.eventType() == EventType.USER_TERMINATED) {
      if (!"TERMINATED".equals(text(user, "employmentStatus"))) {
        throw rule("Termination requires TERMINATED employment status");
      }
      JsonNode date = user.get("terminationDate");
      if (date != null && !date.isNull()) {
        date(user, "terminationDate");
      }
      // Incomplete manager/profile/role data must not prevent revocation.
      return;
    }
    fields(user, PROFILE, "user");
    if (!"ACTIVE".equals(text(user, "employmentStatus"))) {
      throw rule("Provisioning and updates require ACTIVE employment status");
    }
    if (!user.get("terminationDate").isNull()) {
      throw rule("terminationDate must be null for ACTIVE employment");
    }
    if (!Set.of("WORKDAY", "VNDLY").contains(text(user, "sourceSystem"))) {
      throw invalid("sourceSystem must be WORKDAY or VNDLY");
    }
    for (String field : PROFILE) {
      if (!Set.of("middleName", "terminationDate", "manager", "account", "iPassRoles").contains(field)) {
        text(user, field);
      }
    }
    nullableText(user, "middleName");
    email(user, "email");
    LocalDate hire = date(user, "hireDate");
    if (hire.isAfter(event.eventEffectiveAt().atOffset(java.time.ZoneOffset.UTC).toLocalDate())) {
      throw rule("hireDate cannot follow the effective event date");
    }
    timestamp(user, "employeeLastSyncedAt");
    JsonNode manager = user.get("manager");
    fields(manager, MANAGER, "manager");
    for (String f : MANAGER) {
      if (f.equals("middleName")) {
        nullableText(manager, f);
      } else {
        text(manager, f);
      }
    }
    identifier(manager, "employeeId");
    email(manager, "email");
    JsonNode account = user.get("account");
    fields(account, ACCOUNT, "account");
    identifier(account, "application");
    identifier(account, "oktaAccountId");
    JsonNode roles = user.get("iPassRoles");
    if (!roles.isArray()) {
      throw invalid("iPassRoles must be an array; use [] to remove all roles");
    }
    if (roles.size() > 500) {
      throw invalid("iPassRoles exceeds 500 assignments");
    }
    if (event.eventType() == EventType.USER_PROVISIONED && roles.isEmpty()) {
      throw rule("Provisioning requires at least one approved role");
    }
    Set<String> ids = new HashSet<>();
    for (JsonNode role : roles) {
      fields(role, ROLE, "role");
      String roleId = identifier(role, "entitlementValue");
      if (!ids.add(roleId)) {
        throw rule("Duplicate entitlementValue in iPassRoles");
      }
      String name = text(role, "roleName");
      if (!name.matches("APP_Pharos_" + event.environment() + "_[A-Za-z0-9]+_[A-Za-z0-9]+")) {
        throw rule("Role name must follow APP_Pharos_Environment_BusinessGroup_Persona and match the environment");
      }
      text(role, "roleDescription");
      text(role, "displayName");
      text(role, "entitlementType");
      for (String flag : Set.of("isPharosGroup", "isAvailableForRequest", "isPrivileged")) {
        if (!role.get(flag).isBoolean()) {
          throw invalid(flag + " must be a JSON boolean");
        }
      }
      if (!role.get("isPharosGroup").asBoolean()) {
        throw rule("iPassRoles must contain only Pharos entitlements");
      }
      JsonNode owners = role.get("owners");
      if (!owners.isArray() || owners.size() > 100) {
        throw invalid("owners must be an array with at most 100 entries");
      }
      Set<String> ownerIds = new HashSet<>();
      for (JsonNode owner : owners) {
        fields(owner, OWNER, "owner");
        if (!ownerIds.add(identifier(owner, "ownerId"))) {
          throw rule("Duplicate ownerId in role owners");
        }
        text(owner, "firstName");
        text(owner, "lastName");
        email(owner, "email");
      }
      if (!"PROVISIONED".equals(text(role, "assignmentStatus"))) {
        throw rule("Only current PROVISIONED roles belong in the snapshot");
      }
      if (timestamp(role, "assignedAt").isAfter(event.eventEffectiveAt())) {
        throw rule("assignedAt cannot follow eventEffectiveAt");
      }
    }
  }

  private void fields(JsonNode node, Set<String> fields, String label) {
    if (node == null || !node.isObject()) {
      throw invalid(label + " must be an object");
    }
    for (String name : fields) {
      if (!node.has(name)) {
        throw invalid(label + "." + name + " is required");
      }
    }
    for (String name : node.propertyNames()) {
      if (!fields.contains(name)) {
        throw invalid("Unknown field: " + label + "." + name);
      }
    }
  }

  public static String text(JsonNode node, String field) {
    JsonNode v = node.get(field);
    if (v == null || !v.isString() || v.asString().isBlank() || v.asString().length() > 1000 || !v.asString().equals(v.asString().strip())) {
      throw invalid(field + " must be a nonblank string without surrounding whitespace (max 1000 characters)");
    }
    return v.asString();
  }

  private static String identifier(JsonNode node, String field) {
    String value = text(node, field);
    if (value.length() > 128 || value.chars().anyMatch(Character::isISOControl)) {
      throw invalid(field + " must be a valid source identifier (max 128 characters)");
    }
    return value;
  }

  private void nullableText(JsonNode node, String field) {
    if (!node.get(field).isNull()) {
      text(node, field);
    }
  }

  private void email(JsonNode node, String field) {
    if (!validator.validate(new EmailValue(text(node, field))).isEmpty()) {
      throw invalid(field + " must be a valid email address");
    }
  }

  public static Instant timestamp(JsonNode node, String field) {
    try {
      return OffsetDateTime.parse(text(node, field)).toInstant();
    } catch (DateTimeParseException e) {
      throw invalid(field + " must be an RFC 3339 timestamp with timezone");
    }
  }

  public static LocalDate date(JsonNode node, String field) {
    try {
      return LocalDate.parse(text(node, field));
    } catch (DateTimeParseException e) {
      throw invalid(field + " must be a valid YYYY-MM-DD date");
    }
  }

  private record EmailValue(@Email String value) {}
}
